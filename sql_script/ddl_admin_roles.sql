-- ============================================================
-- BODIFY - admin console: roles a superadmin defines, and what they allow
--
--   permissions             the fixed list the API enforces (one row per
--                           function + action, e.g. foods.update). Seeded
--                           here, mirrored by app/core/permissions.py; the
--                           console never writes it - a key no route checks
--                           would be a checkbox that grants nothing.
--   admin_roles             named roles a superadmin creates in the console.
--   admin_role_permissions  which permissions each role carries.
--   user_admin_roles        which roles each person holds (any number; what
--                           they may do is the union).
--
-- user_profiles.role widens to user / admin / superadmin:
--   admin       has at least one role; may do what those roles allow.
--   superadmin  may do everything, and is the only one who manages roles
--               and assigns them. Not a role in admin_roles on purpose:
--               whoever could manage roles could grant themselves the rest.
--
-- Every existing admin is given the role "Toàn quyền" (every permission), so
-- nobody loses access when this ships. A superadmin trims it afterwards.
--
-- Row level security is enabled on the four new tables with no policies:
-- the API connects as the database owner and bypasses it, while the
-- PostgREST roles (anon, authenticated) can neither read nor write them.
--
-- Idempotent. Deploy order (CLAUDE.md §2):
--   1. this script                (the old backend keeps working: it only
--                                  ever compares role to 'admin')
--   2. push the backend
--   3. make the first superadmin, AFTER the deploy - the old backend refuses
--      any role but 'admin', so doing it earlier locks that person out:
--        UPDATE user_profiles SET role = 'superadmin', updated_at = now()
--         WHERE user_id = (SELECT id FROM auth.users WHERE email = '<email>');
--        DELETE FROM user_admin_roles
--         WHERE user_id = (SELECT id FROM auth.users WHERE email = '<email>');
--   4. ship the console
-- Undo: rollback_admin_roles.sql
-- ============================================================

BEGIN;

ALTER TABLE user_profiles DROP CONSTRAINT IF EXISTS chk_user_profiles_role;
ALTER TABLE user_profiles
    ADD CONSTRAINT chk_user_profiles_role CHECK (role IN ('user', 'admin', 'superadmin'));

CREATE TABLE IF NOT EXISTS permissions (
    permission_key VARCHAR(40) PRIMARY KEY,
    function_key   VARCHAR(30) NOT NULL,
    action         VARCHAR(20) NOT NULL,
    group_name     VARCHAR(40) NOT NULL,
    label          VARCHAR(80) NOT NULL,
    sort_order     INTEGER     NOT NULL,
    CONSTRAINT chk_permissions_key CHECK (permission_key = function_key || '.' || action)
);

INSERT INTO permissions (permission_key, function_key, action, group_name, label, sort_order) VALUES
