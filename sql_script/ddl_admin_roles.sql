    ('exercises.delete', 'exercises', 'delete', 'Tập luyện',  'Xoá bài tập, nhóm cơ, thiết bị',    90),
    ('foods.view',       'foods',     'view',   'Dinh dưỡng', 'Xem thực phẩm, nhóm thực phẩm',    100),
    ('foods.create',     'foods',     'create', 'Dinh dưỡng', 'Thêm thực phẩm, nhóm thực phẩm',   110),
    ('foods.update',     'foods',     'update', 'Dinh dưỡng', 'Sửa thực phẩm, nhóm thực phẩm',    120),
    ('foods.delete',     'foods',     'delete', 'Dinh dưỡng', 'Xoá thực phẩm, nhóm thực phẩm',    130)
ON CONFLICT (permission_key) DO UPDATE SET
    function_key = EXCLUDED.function_key,
    action       = EXCLUDED.action,
    group_name   = EXCLUDED.group_name,
    label        = EXCLUDED.label,
    sort_order   = EXCLUDED.sort_order;

CREATE TABLE IF NOT EXISTS admin_roles (
    admin_role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60) NOT NULL,
    description   TEXT,
    created_by    UUID,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_admin_roles_name CHECK (btrim(name) <> '')
);
-- "Biên tập" and "biên tập" are the same role to a person reading the list.
CREATE UNIQUE INDEX IF NOT EXISTS uq_admin_roles_name ON admin_roles (lower(btrim(name)));

CREATE TABLE IF NOT EXISTS admin_role_permissions (
    admin_role_id  INTEGER     NOT NULL,
    permission_key VARCHAR(40) NOT NULL,
    PRIMARY KEY (admin_role_id, permission_key),
    CONSTRAINT fk_admin_role_permissions_role FOREIGN KEY (admin_role_id)
        REFERENCES admin_roles (admin_role_id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_role_permissions_permission FOREIGN KEY (permission_key)
        REFERENCES permissions (permission_key) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_admin_role_permissions_permission
    ON admin_role_permissions (permission_key);

CREATE TABLE IF NOT EXISTS user_admin_roles (
    user_id       UUID        NOT NULL,
    admin_role_id INTEGER     NOT NULL,
    assigned_by   UUID,
    assigned_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, admin_role_id),
    CONSTRAINT fk_user_admin_roles_user FOREIGN KEY (user_id)
        REFERENCES user_profiles (user_id) ON DELETE CASCADE,
    -- RESTRICT: deleting a role people hold would take their access away
    -- without anyone being told. The API answers 409 with the count first.
    CONSTRAINT fk_user_admin_roles_role FOREIGN KEY (admin_role_id)
        REFERENCES admin_roles (admin_role_id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS ix_user_admin_roles_role ON user_admin_roles (admin_role_id);

ALTER TABLE permissions            ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_roles            ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_role_permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_admin_roles       ENABLE ROW LEVEL SECURITY;

-- Existing admins keep everything they could do yesterday.
INSERT INTO admin_roles (name, description)
SELECT 'Toàn quyền', 'Mọi quyền trong bảng quản trị (tạo khi chuyển sang phân quyền theo vai trò).'
WHERE NOT EXISTS (SELECT 1 FROM admin_roles WHERE lower(btrim(name)) = lower('Toàn quyền'));

INSERT INTO admin_role_permissions (admin_role_id, permission_key)
SELECT r.admin_role_id, p.permission_key
FROM admin_roles r CROSS JOIN permissions p
WHERE lower(btrim(r.name)) = lower('Toàn quyền')
ON CONFLICT DO NOTHING;

INSERT INTO user_admin_roles (user_id, admin_role_id)
SELECT up.user_id, r.admin_role_id
FROM user_profiles up
JOIN admin_roles r ON lower(btrim(r.name)) = lower('Toàn quyền')
WHERE up.role = 'admin'
  AND NOT EXISTS (SELECT 1 FROM user_admin_roles u WHERE u.user_id = up.user_id)
ON CONFLICT DO NOTHING;

COMMIT;

