    ('costs.view',       'costs',     'view',   'Tổng quan',  'Xem chi phí vận hành',              30),
    ('users.view',       'users',     'view',   'Người dùng', 'Xem tài khoản',                     40),
    ('users.ban',        'users',     'ban',    'Người dùng', 'Khoá / mở khoá tài khoản',          50),
